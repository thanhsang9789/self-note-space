-- 1. Letters & Personal Notes table
create table if not exists public.letters (
  id bigint generated by default as identity primary key,
  client_id text unique,
  owner_id uuid references auth.users(id) on delete cascade,
  is_private boolean not null default false,
  recipient text not null check (char_length(recipient) between 1 and 60),
  message text not null check (char_length(message) between 1 and 2000),
  space text not null default 'Global',
  color_hex text not null default '#ffe082',
  template_id text check (template_id in ('love', 'celebration') or template_id is null),
  hearts_count integer not null default 0,
  reports integer not null default 0,
  is_hidden boolean not null default false,
  spotlight_expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_letters_space_created on public.letters (space, created_at desc);
create index if not exists idx_letters_owner on public.letters (owner_id, created_at desc);

-- 2. Custom Note Spaces table (synced per authenticated user)
create table if not exists public.custom_spaces (
  id uuid default gen_random_uuid() primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  slug text not null,
  name text not null,
  emoji text not null default '📝',
  is_private boolean not null default true,
  created_at timestamptz not null default now(),
  unique (owner_id, slug)
);

-- 3. Enable Row Level Security (RLS)
alter table public.letters enable row level security;
alter table public.custom_spaces enable row level security;

-- Public feed letters (Global & Campuses) are readable by everyone when not hidden;
-- Private personal notes are readable ONLY by their authenticated owner.
drop policy if exists "Read public letters or own private notes" on public.letters;
create policy "Read public letters or own private notes"
  on public.letters for select
  using (
    (is_private = false and is_hidden = false)
    or (auth.uid() is not null and owner_id = auth.uid())
  );

-- Anyone can post anonymous public letters; private notes require owner_id = auth.uid()
drop policy if exists "Insert public letters or own private notes" on public.letters;
create policy "Insert public letters or own private notes"
  on public.letters for insert
  with check (
    (is_private = false and owner_id is null)
    or (auth.uid() is not null and owner_id = auth.uid())
  );

-- Owners can edit/pin/delete their own notes; public letters allow heart/report updates via RPC
drop policy if exists "Owners update own notes" on public.letters;
create policy "Owners update own notes"
  on public.letters for update
  using (auth.uid() is not null and owner_id = auth.uid())
  with check (auth.uid() is not null and owner_id = auth.uid());

drop policy if exists "Owners delete own notes" on public.letters;
create policy "Owners delete own notes"
  on public.letters for delete
  using (auth.uid() is not null and owner_id = auth.uid());

-- Custom spaces belong strictly to their authenticated owner
drop policy if exists "Manage own custom spaces" on public.custom_spaces;
create policy "Manage own custom spaces"
  on public.custom_spaces for all
  using (auth.uid() = owner_id)
  with check (auth.uid() = owner_id);

-- 4. Safe atomic RPC functions for anonymous Hearts & Reports on public letters
create or replace function public.toggle_letter_heart(target_id bigint, delta integer)
returns integer
language plpgsql
security definer
as $$
declare
  new_count integer;
begin
  update public.letters
  set hearts_count = greatest(0, hearts_count + greatest(-1, least(1, delta)))
  where id = target_id and is_private = false
  returning hearts_count into new_count;
  return coalesce(new_count, 0);
end;
$$;

create or replace function public.report_public_letter(target_id bigint)
returns void
language plpgsql
security definer
as $$
begin
  update public.letters
  set reports = reports + 1,
      is_hidden = case when reports + 1 >= 5 then true else is_hidden end
  where id = target_id and is_private = false;
end;
$$;
